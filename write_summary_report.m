function write_summary_report(cfg, baseline_res, traces, disp_res, sweep, mc)
% WRITE_SUMMARY_REPORT  Plain-text summary of the whole workflow, computed
% entirely from the passed-in results. Writes outputs/summary_report.txt.

p = cfg.baseline;  b = baseline_res.best;  d = cfg.dispatch;
f = fullfile(cfg.out.dir, 'summary_report.txt');
fid = fopen(f, 'w');
if fid < 0, error('write_summary_report:io', 'cannot open %s', f); end
c = @(varargin) fprintf(fid, varargin{:});

c('BESS / DATA-CENTER CAPACITY PLANNING -- SUMMER EXTENSION REPORT\n');
c('generated: %s\n', datestr(now));
c('================================================================\n\n');

c('1. BASELINE OPTIMAL DESIGN (closed-form chance constraint)\n');
c('   demand target %.0f kW, service probability %.1f%% (eps = %g)\n', ...
  p.demand_total, 100*(1-p.eps), p.eps);
c('   N = %d racks | grid feed P_ref = %.1f kW\n', b.N, b.P_ref);
c('   BESS: %.1f kW / %.1f kWh | supercap: %.3f kWh/rack (%.1f kWh total)\n', ...
  b.P_bess, b.C_bess, b.C_sc_per_rack, b.C_sc_total);
c('   sigma_agg = %.1f kW vs %.1f kW unmultiplexed (%.0f%% reduction)\n', ...
  b.sigma_agg, b.N*p.sigma, 100*(1 - b.sigma_agg/(b.N*p.sigma)));
c('   capex $%.0f | grid energy $%.0f | total $%.0f over %.0f yr\n\n', ...
  b.capex, b.grid, b.total, p.horizon_h/8760);

c('2. LOAD TRACES (%s)\n', traces.source);
c('   %d racks x %d steps, dt = %.0f s (%.1f days)\n', ...
  traces.N, numel(traces.t_h), traces.dt_h*3600, ...
  numel(traces.t_h)*traces.dt_h/24);
c('   aggregate: mean %.1f kW, std %.1f kW, peak %.1f kW\n', ...
  mean(traces.agg_total), std(traces.agg_total), max(traces.agg_total));
c('   burst component mean %.2f kW (absorbed by the supercap layer)\n\n', ...
  mean(traces.agg_burst));

c('3. TIME-INDEXED DISPATCH VALIDATION (slow layer)\n');
c('   BESS %.1f kW / %.1f kWh, eta_rt = %.2f, SOC window %.0f-%.0f%%\n', ...
  b.P_bess, b.C_bess, d.eta_rt, 100*d.soc_min, 100*d.soc_max);
c('   band exceedance P[L > P_ref + P_bess]: %.4f (theory bound eps = %g)\n', ...
  disp_res.band_exceed_rate, p.eps);
c('   unmet after SOC/efficiency limits  : %.4f of steps\n', ...
  disp_res.violation_rate);
c('   peak unmet %.1f kW | unmet energy %.2f kWh | SOC at floor %.2f%% of time\n', ...
  disp_res.peak_unmet_kW, disp_res.unmet_energy_kWh, 100*disp_res.soc_at_min_frac);
if disp_res.violation_rate > disp_res.band_exceed_rate + 1e-9
    c(['   NOTE: unmet rate exceeds the marginal band rate -- energy/SOC\n' ...
       '   limits bind during persistent excursions; the closed-form\n' ...
       '   C_bess = P_bess*tau_bess window heuristic is the weak link.\n']);
end
c('\n');

c('4. MONTE CARLO VALIDATION OF THE CHANCE CONSTRAINT\n');
c('   per-rack equicorrelated Gaussian trials, iid in time (marginal test)\n');
c('   %-6s %-10s %-14s %-10s %s\n', 'rho', 'eps', 'empirical', 'SE', 'verdict');
for i = 1:size(mc.rows,1)
    vc = mc.rows(i,9);
    if vc < 0, vs = 'conservative'; elseif vc > 0, vs = 'optimistic';
    else, vs = 'accurate'; end
    c('   %-6.2f %-10.3f %-14.5f %-10.5f %s\n', ...
      mc.rows(i,1), mc.rows(i,2), mc.rows(i,6), mc.rows(i,7), vs);
end
nacc = sum(mc.rows(:,9) == 0);
c('   %d of %d scenarios within 3 standard errors of target.\n\n', ...
  nacc, size(mc.rows,1));

c('5. SENSITIVITY (from sensitivity_results.csv)\n');
c('   P_bess grows with rho: %.1f kW at rho=%.1f -> %.1f kW at rho=%.1f\n', ...
  sweep.Pbess_vs_rho(1), sweep.rho_grid(1), ...
  sweep.Pbess_vs_rho(end), sweep.rho_grid(end));
c('   total cost across eps grid [%g .. %g]: $%.0f .. $%.0f\n', ...
  min(sweep.eps_grid), max(sweep.eps_grid), ...
  min(sweep.costM(:)), max(sweep.costM(:)));
c('   doubling c_bess_P from baseline changes total by $%.0f\n', ...
  interp_cost(sweep.cP_grid, sweep.cost_vs_cP, 2*p.c_bess_P) - ...
  interp_cost(sweep.cP_grid, sweep.cost_vs_cP, p.c_bess_P));
c('   doubling c_bess_E from baseline changes total by $%.0f\n', ...
  interp_cost(sweep.cE_grid, sweep.cost_vs_cE, 2*p.c_bess_E) - ...
  interp_cost(sweep.cE_grid, sweep.cost_vs_cE, p.c_bess_E));
c('   (grid energy dominates total cost, so BESS-price sensitivity is small\n');
c('    in absolute terms but large relative to storage capex.)\n\n');

c('6. LIMITATIONS\n');
c(['   - marginal (per-instant) chance constraint; no joint guarantee over\n' ...
   '     intervals; dispatch validation partially covers this gap\n' ...
   '   - C_bess = P_bess * tau_bess is a window heuristic, not derived from\n' ...
   '     the fluctuation spectrum\n' ...
   '   - Gaussian loads clipped at zero; real workloads are heavier-tailed\n' ...
   '   - flat energy price; no demand charges, TOU tariffs, or degradation\n' ...
   '   - supercap layer assumed to absorb all fast bursts perfectly\n\n']);

c('7. RECOMMENDED NEXT STEPS\n');
c(['   - fit mu, sigma, rho, burst statistics from real rack/GPU traces\n' ...
   '     (drop a CSV named real_load_data.csv to use it automatically)\n' ...
   '   - derive C_bess from the autocorrelation of measured fluctuations\n' ...
   '   - add an interval/joint chance constraint and re-validate\n' ...
   '   - add TOU tariff + demand charges; re-run sweeps\n' ...
   '   - model BESS degradation (cycle counting from dispatch throughput)\n']);

fclose(fid);
fprintf('Wrote %s\n', f);
end

function y = interp_cost(xg, yg, x)
y = interp1(xg(:), yg(:), x, 'linear', 'extrap');
end
